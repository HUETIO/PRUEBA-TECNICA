#!/usr/bin/env python3
"""Create a private local .env and synchronize evaluator-only credentials."""
from __future__ import annotations

import base64
import json
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"
MANIFEST_PATH = ROOT / "entrega.yaml"


def new_env() -> dict[str, str]:
    return {
        "PG_HOST": "localhost",
        "PG_PORT": "5432",
        "PG_DATABASE": "bia_datos",
        "PG_SUPERUSER": "postgres",
        "PG_SUPERPASSWORD": secrets.token_urlsafe(32),
        "PG_INGEST_USER": "rol_ingesta",
        "PG_INGEST_PASSWORD": secrets.token_urlsafe(32),
        "PG_ANALYST_USER": "rol_analista",
        "PG_ANALYST_PASSWORD": secrets.token_urlsafe(32),
        "PG_AUDITOR_USER": "rol_auditor",
        "PG_AUDITOR_PASSWORD": secrets.token_urlsafe(32),
        "APP_ENCRYPTION_KEY": base64.urlsafe_b64encode(
            secrets.token_bytes(32)
        ).decode("ascii"),
        "KAFKA_BOOTSTRAP": "localhost:9092",
        "KAFKA_TOPIC": "mediciones.raw",
    }


def read_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if ENV_PATH.exists():
        for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and "=" in stripped:
                key, value = stripped.split("=", 1)
                values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def write_env(values: dict[str, str]) -> None:
    comments = (
        "# Local-only credentials generated by tools/bootstrap.py. Do not commit.\n"
        "# Regenerate only after removing the local Docker volume.\n"
    )
    ENV_PATH.write_text(
        comments + "".join(f"{key}={value}\n" for key, value in values.items()),
        encoding="utf-8",
    )
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass


def sync_manifest(values: dict[str, str]) -> None:
    text = MANIFEST_PATH.read_text(encoding="utf-8")
    credentials = [
        (values["PG_SUPERUSER"], values["PG_SUPERPASSWORD"]),
        (values["PG_INGEST_USER"], values["PG_INGEST_PASSWORD"]),
        (values["PG_ANALYST_USER"], values["PG_ANALYST_PASSWORD"]),
        (values["PG_AUDITOR_USER"], values["PG_AUDITOR_PASSWORD"]),
    ]
    for field, column in (("usuario", 0), ("password", 1)):
        index = 0

        def substitute(match: re.Match[str]) -> str:
            nonlocal index
            if index >= len(credentials):
                raise ValueError(f"Too many {field} entries in entrega.yaml")
            value = credentials[index][column]
            index += 1
            return f"{match.group(1)}{json.dumps(value)}{match.group(3)}"

        text, count = re.subn(
            rf'(?m)^(\s*{field}:\s*)("[^"]*"|[^#\r\n]*?)(\s*(?:#.*)?)$',
            substitute,
            text,
        )
        if count != len(credentials) or index != len(credentials):
            raise ValueError(
                f"Expected exactly four {field} fields in entrega.yaml, found {count}"
            )
    for field, value in (
        ("host", values["PG_HOST"]),
        ("port", values["PG_PORT"]),
        ("database", values["PG_DATABASE"]),
    ):
        pattern = rf"(?m)^(\s*{field}:\s*)([^#\r\n]+?)(\s*(?:#.*)?)$"
        text, count = re.subn(
            pattern,
            lambda match: f"{match.group(1)}{value}{match.group(3)}",
            text,
            count=1,
        )
        if count != 1:
            raise ValueError(f"Expected one postgres.{field} field in entrega.yaml")
    MANIFEST_PATH.write_text(text, encoding="utf-8")


def main() -> int:
    values = read_env()
    if not values:
        values = new_env()
        write_env(values)
        print("Created local credentials in .env (ignored by Git).")
    required = set(new_env()) - {
        "PG_HOST", "PG_PORT", "PG_DATABASE", "KAFKA_BOOTSTRAP", "KAFKA_TOPIC"
    }
    missing = sorted(key for key in required if not values.get(key) or values[key] == "cambiame")
    if missing:
        print(
            "Invalid local .env. Remove placeholders or remove .env to generate "
            f"ephemeral credentials. Missing/placeholder keys: {', '.join(missing)}",
            file=sys.stderr,
        )
        return 1
    try:
        sync_manifest(values)
    except (OSError, ValueError) as exc:
        print(f"Could not synchronize entrega.yaml: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
